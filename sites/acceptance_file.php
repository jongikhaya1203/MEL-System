<?php
/**
 * Serves an acceptance form image to logged-in users.
 * ?id=<site id>&type=site_sig|usaasa_sig|power_proof|speed_proof
 */
require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/functions.php';
require_login();

$columns = [
    'site_sig'    => 'site_rep_signature',
    'usaasa_sig'  => 'usaasa_rep_signature',
    'power_proof' => 'backup_power_proof',
    'speed_proof' => 'speed_proof',
];
$siteId = (int)($_GET['id'] ?? 0);
$type = $_GET['type'] ?? '';
if (!isset($columns[$type])) {
    http_response_code(400);
    die('Invalid file type.');
}

$stmt = $pdo->prepare("SELECT {$columns[$type]} FROM site_acceptance_forms WHERE site_id = ?");
$stmt->execute([$siteId]);
$filename = $stmt->fetchColumn();

// Filenames are only ever generated by store_signature_data_url() / store_acceptance_proof_upload().
if (!$filename || !preg_match('/^(signature|proof)_[0-9a-f]{32}\.(png|jpg)$/', $filename, $m)
    || !is_file(ACCEPTANCE_STORAGE_DIR . $filename)) {
    http_response_code(404);
    die('File not found.');
}

$path = ACCEPTANCE_STORAGE_DIR . $filename;
header('Content-Type: ' . ($m[2] === 'png' ? 'image/png' : 'image/jpeg'));
header('Content-Length: ' . filesize($path));
header('Content-Disposition: inline; filename="' . $filename . '"');
header('Cache-Control: private, no-cache');
header('X-Content-Type-Options: nosniff');
readfile($path);
