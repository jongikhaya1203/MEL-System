<?php
require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/csrf.php';
require_once __DIR__ . '/../includes/functions.php';
require_role(['admin', 'manager']);

$periodType = $_GET['period_type'] ?? '';
$where = [];
$params = [];
if ($periodType !== '' && in_array($periodType, ['Monthly', 'Quarterly', 'Half-Yearly', 'Yearly'], true)) {
    $where[] = 'r.period_type = ?';
    $params[] = $periodType;
}

$sql = "SELECT r.id, r.period_type, r.period_label, r.period_start, r.period_end, r.generated_at, u.full_name AS generated_by_name
        FROM ai_reports r JOIN users u ON u.id = r.generated_by";
if ($where) {
    $sql .= ' WHERE ' . implode(' AND ', $where);
}
$sql .= ' ORDER BY r.period_start DESC, r.generated_at DESC';
$stmt = $pdo->prepare($sql);
$stmt->execute($params);
$reports = $stmt->fetchAll();

$pageTitle = 'AI Reports';
include __DIR__ . '/../includes/header.php';
?>
<div class="page-header">
    <div>
        <h1>AI Reports</h1>
        <p class="subtitle">Automated, integrated reports across every module &mdash; Monthly, Quarterly, Half-Yearly, Yearly</p>
    </div>
    <a class="btn" href="<?= APP_BASE_URL ?>/ai_reports/generate.php">+ Generate report</a>
</div>

<div class="card">
    <form method="get" class="form-grid">
        <div class="field">
            <label for="period_type">Period type</label>
            <select id="period_type" name="period_type" onchange="this.form.submit()">
                <option value="">All period types</option>
                <?php foreach (['Monthly', 'Quarterly', 'Half-Yearly', 'Yearly'] as $t): ?>
                    <option value="<?= $t ?>" <?= $periodType === $t ? 'selected' : '' ?>><?= $t ?></option>
                <?php endforeach; ?>
            </select>
        </div>
        <div class="field">
            <button type="submit" class="btn btn-secondary">Filter</button>
            <a class="btn btn-secondary" href="<?= APP_BASE_URL ?>/ai_reports/list.php">Reset</a>
        </div>
    </form>
</div>

<div class="card">
    <div class="table-wrap">
    <table>
        <thead><tr><th>Period type</th><th>Period</th><th>Covers</th><th>Generated by</th><th>Generated at</th><th></th></tr></thead>
        <tbody>
        <?php foreach ($reports as $r): ?>
            <tr>
                <td><?= e($r['period_type']) ?></td>
                <td><strong><?= e($r['period_label']) ?></strong></td>
                <td><?= format_date($r['period_start']) ?> &ndash; <?= format_date($r['period_end']) ?></td>
                <td><?= e($r['generated_by_name']) ?></td>
                <td><?= format_datetime($r['generated_at']) ?></td>
                <td><a href="<?= APP_BASE_URL ?>/ai_reports/view.php?id=<?= (int)$r['id'] ?>">View</a></td>
            </tr>
        <?php endforeach; ?>
        <?php if (!$reports): ?>
            <tr><td colspan="6">No reports generated yet. <a href="<?= APP_BASE_URL ?>/ai_reports/generate.php">Generate the first one</a>.</td></tr>
        <?php endif; ?>
        </tbody>
    </table>
    </div>
    <p class="hint" style="margin-top:8px;">Each report is a frozen snapshot — reopening an old report shows exactly what was computed at the time, even if the underlying data has changed since.</p>
</div>

<?php include __DIR__ . '/../includes/footer.php'; ?>
